"""Image synthesis and augmentation for synthetic registration pretraining."""

from __future__ import annotations

import functools
import math

import torch
import torch.nn.functional as F

from psmareg.config.synthetic_pretraining_config import AugmentationConfig
from psmareg.models.common.registration.warping import warp_image_3d


def independent_pet_intensity_augmentation(
    pet: torch.Tensor,
    scale_log_std: float,
    gamma_range: float,
    bias_range: float,
) -> torch.Tensor:
    """Apply per-sample PET SUV-like scale/gamma changes independently.

    Synthetic fixed PET is generated by warping the moving PET, so without this
    step both images share exactly the same p99/preprocessing scale. Real
    baseline/follow-up pairs are normalized independently, so this augmentation
    teaches the registration model not to rely on identical PET absolute scale.

    Args:
        pet: Normalized PET of shape ``[B, 1, D, H, W]``.
        scale_log_std: Standard deviation of the log-normal uptake scale.
        gamma_range: Half-width of the uniform gamma range around one.
        bias_range: Half-width of the uniform additive bias.

    Returns:
        Augmented PET clipped to ``[0, 1]``.
    """
    if scale_log_std <= 0.0 and gamma_range <= 0.0 and bias_range <= 0.0:
        return pet

    shape = (pet.shape[0],) + (1,) * (pet.ndim - 1)
    augmented = pet.float().clamp(0.0, 1.0)

    if scale_log_std > 0.0:
        scale = torch.exp(
            torch.randn(shape, device=pet.device, dtype=augmented.dtype) *
            scale_log_std)
        augmented = augmented * scale

    if gamma_range > 0.0:
        gamma_low = max(0.05, 1.0 - gamma_range)
        gamma_high = 1.0 + gamma_range
        gamma = torch.empty(
            shape,
            device=pet.device,
            dtype=augmented.dtype,
        ).uniform_(gamma_low, gamma_high)
        augmented = augmented.clamp(0.0, 1.0).pow(gamma)

    if bias_range > 0.0:
        bias = torch.empty(
            shape,
            device=pet.device,
            dtype=augmented.dtype,
        ).uniform_(-bias_range, bias_range)
        augmented = augmented + bias

    return augmented.clamp(0.0, 1.0).to(dtype=pet.dtype)


def random_smooth_bias_like(
    image: torch.Tensor,
    amplitude: float,
    spacing: int = 32,
) -> torch.Tensor:
    """Sample a low-frequency bias field for synthetic image styling.

    Args:
        image: Image whose shape, device, and dtype are reproduced.
        amplitude: Maximum absolute value of the bias field.
        spacing: Voxel spacing of the random control points.

    Returns:
        Smooth bias field with the shape of ``image``.
    """
    if amplitude <= 0.0:
        return torch.zeros_like(image)

    low_shape = tuple(
        max(2, math.ceil(size / spacing)) for size in image.shape[-3:])
    low_noise = torch.randn(
        image.shape[0],
        1,
        *low_shape,
        device=image.device,
        dtype=image.dtype,
    )
    smooth = F.interpolate(
        low_noise,
        size=image.shape[-3:],
        mode="trilinear",
        align_corners=False,
    )
    smooth = smooth / smooth.abs().amax(dim=(2, 3, 4),
                                        keepdim=True).clamp_min(1e-6)
    return amplitude * smooth


def random_average_blur(image: torch.Tensor,
                        probability: float = 0.5) -> torch.Tensor:
    """Cheap random blur used only for synthetic style augmentation."""
    if float(torch.rand((), device=image.device)) >= probability:
        return image
    kernel_size = 3 if float(torch.rand((), device=image.device)) < 0.7 else 5
    padding = kernel_size // 2
    return F.avg_pool3d(
        image,
        kernel_size=kernel_size,
        stride=1,
        padding=padding,
    )


def random_resolution_augmentation(
    image: torch.Tensor,
    probability: float,
    min_scale: float,
) -> torch.Tensor:
    """Random anisotropic low-resolution resampling, inspired by SynthMorph.

    Args:
        image: Image of shape ``[B, C, D, H, W]``.
        probability: Probability of degrading the resolution.
        min_scale: Smallest per-axis resolution scale that can be drawn.

    Returns:
        Image resampled back to its original shape.
    """
    if probability <= 0.0 or float(torch.rand(
        (), device=image.device)) >= probability:
        return image
    min_scale = max(0.25, min(min_scale, 1.0))
    spatial_shape = image.shape[-3:]
    scales = torch.empty(3, device=image.device).uniform_(min_scale, 1.0)
    # Keep at least one axis close to native resolution in many samples; real
    # scans often degrade primarily through slice thickness or reconstruction.
    if float(torch.rand((), device=image.device)) < 0.65:
        axis_to_keep = int(torch.randint(0, 3, (), device=image.device).item())
        scales[axis_to_keep] = 1.0
    low_shape = tuple(
        max(2, int(round(size * float(scale.cpu()))))
        for size, scale in zip(spatial_shape, scales, strict=True))
    low = F.interpolate(
        image,
        size=low_shape,
        mode="trilinear",
        align_corners=False,
    )
    return F.interpolate(
        low,
        size=spatial_shape,
        mode="trilinear",
        align_corners=False,
    )


def ct_label_to_random_synthetic_ct(
    label: torch.Tensor,
    noise_std: float,
    bias_amplitude: float,
) -> torch.Tensor:
    """Generate a CT-like image from labels with random per-class contrast.

    Args:
        label: Anatomy labels of shape ``[B, 1, D, H, W]``.
        noise_std: Standard deviation of the additive Gaussian noise.
        bias_amplitude: Amplitude of the additive smooth bias field.

    Returns:
        CT-like image in ``[0, 1]`` with dark air.
    """
    label_long = label.long()
    output = torch.zeros(
        label_long.shape,
        device=label_long.device,
        dtype=torch.float32,
    )

    for batch_idx in range(label_long.shape[0]):
        sample_label = label_long[batch_idx]
        sample = output[batch_idx]
        classes = torch.unique(sample_label)
        for class_index in classes:
            if int(class_index.item()) == 0:
                intensity = torch.empty(
                    (),
                    device=label_long.device,
                    dtype=torch.float32,
                ).uniform_(0.0, 0.08)
            else:
                # Wide random CT window values: this deliberately breaks
                # intensity identity and keeps anatomy/shape as the cue.
                intensity = torch.empty(
                    (),
                    device=label_long.device,
                    dtype=torch.float32,
                ).uniform_(0.12, 0.92)
            sample[sample_label == class_index] = intensity

    body = (label_long > 0).float()
    output = output + random_smooth_bias_like(output, amplitude=bias_amplitude)
    if noise_std > 0.0:
        output = output + torch.randn_like(output) * noise_std
    output = random_average_blur(output, probability=0.4)
    output = output * body + output.clamp(0.0, 0.08) * (1.0 - body)
    return output.clamp(0.0, 1.0)


def label_to_random_synthetic_pet(
    ct_label: torch.Tensor,
    pet_label: torch.Tensor | None,
    noise_std: float,
    lesion_dropout_probability: float,
    false_hot_probability: float,
) -> torch.Tensor:
    """Generate PET-like uptake with independently missing/extra hot regions.

    Args:
        ct_label: Anatomy labels of shape ``[B, 1, D, H, W]``.
        pet_label: Optional lesion labels with the same shape.
        noise_std: Standard deviation of the additive Gaussian noise.
        lesion_dropout_probability: Probability of hiding the annotated lesions.
        false_hot_probability: Probability of adding an unannotated hot region.

    Returns:
        PET-like image in ``[0, 1]``, zero outside the body.
    """
    body = (ct_label.long() > 0).float()
    shape = (ct_label.shape[0], 1, 1, 1, 1)
    baseline_uptake = torch.empty(
        shape,
        device=ct_label.device,
        dtype=torch.float32,
    ).uniform_(0.015, 0.12)
    pet = body * baseline_uptake
    pet = pet + body * random_smooth_bias_like(pet, amplitude=0.08,
                                               spacing=40).clamp_min(0.0)

    if pet_label is not None:
        hot = (pet_label.long() > 0).float()
        keep = (torch.rand(shape, device=ct_label.device, dtype=torch.float32)
                >= lesion_dropout_probability).float()
        hot_scale = torch.empty(
            shape,
            device=ct_label.device,
            dtype=torch.float32,
        ).uniform_(0.55, 1.0)
        pet = pet + hot * keep * hot_scale

    if false_hot_probability > 0.0:
        for batch_idx in range(ct_label.shape[0]):
            if float(torch.rand(
                (), device=ct_label.device)) >= false_hot_probability:
                continue
            smooth_noise = random_smooth_bias_like(
                pet[batch_idx:batch_idx + 1],
                amplitude=1.0,
                spacing=28,
            )
            false_hot = (smooth_noise > torch.quantile(smooth_noise.flatten(),
                                                       0.985)).float()
            pet[batch_idx:batch_idx +
                1] = (pet[batch_idx:batch_idx + 1] +
                      false_hot * body[batch_idx:batch_idx + 1] * 0.45)

    if noise_std > 0.0:
        pet = pet + torch.randn_like(pet) * noise_std
    pet = random_average_blur(pet, probability=0.25)
    return pet.clamp(0.0, 1.0)


def apply_independent_fov_dropout(
    ct: torch.Tensor,
    pet: torch.Tensor,
    probability: float,
    max_fraction: float,
) -> tuple[torch.Tensor, torch.Tensor, bool]:
    """Truncate one random spatial side to mimic longitudinal FOV mismatch.

    Args:
        ct: CT of shape ``[B, 1, D, H, W]``.
        pet: PET with the same shape, truncated identically.
        probability: Probability of truncating each sample.
        max_fraction: Largest fraction of one axis that can be removed.

    Returns:
        Truncated CT and PET, and whether any sample was truncated.
    """
    if probability <= 0.0 or max_fraction <= 0.0:
        return ct, pet, False

    applied = False
    ct_out = ct
    pet_out = pet
    for batch_idx in range(ct.shape[0]):
        if float(torch.rand((), device=ct.device)) >= probability:
            continue
        axis = int(torch.randint(0, 3, (), device=ct.device).item())
        spatial_size = ct.shape[-3 + axis]
        max_voxels = max(1, int(round(spatial_size * max_fraction)))
        cut = int(torch.randint(1, max_voxels + 1, (), device=ct.device).item())
        from_low_side = bool(torch.rand((), device=ct.device) < 0.5)
        mask = torch.ones_like(ct[batch_idx:batch_idx + 1])
        spatial_dim = 2 + axis
        slices: list[slice] = [slice(None)] * mask.ndim
        slices[spatial_dim] = slice(0, cut) if from_low_side else slice(
            spatial_size - cut, spatial_size)
        mask[tuple(slices)] = 0.0
        ct_out = ct_out.clone() if ct_out.data_ptr() == ct.data_ptr(
        ) else ct_out
        pet_out = pet_out.clone() if pet_out.data_ptr() == pet.data_ptr(
        ) else pet_out
        ct_out[batch_idx:batch_idx + 1] = ct_out[batch_idx:batch_idx + 1] * mask
        pet_out[batch_idx:batch_idx +
                1] = pet_out[batch_idx:batch_idx + 1] * mask
        applied = True
    return ct_out, pet_out, applied


def synthmorph_like_pair_from_labels(
    moving_ct_label: torch.Tensor,
    moving_pet_label: torch.Tensor | None,
    target_displacement: torch.Tensor,
    augmentation: AugmentationConfig,
    padding_mode: str,
) -> tuple[torch.Tensor, torch.Tensor, torch.Tensor, torch.Tensor, bool]:
    """Create independently styled fixed/moving images from the same labels.

    Args:
        moving_ct_label: Moving anatomy labels of shape ``[B, 1, D, H, W]``.
        moving_pet_label: Optional moving lesion labels with the same shape.
        target_displacement: Known field mapping the fixed to the moving grid.
        augmentation: Noise, dropout, and resolution settings.
        padding_mode: Padding used when warping the labels.

    Returns:
        Moving CT, moving PET, fixed CT, fixed PET, and whether a field-of-view
        dropout was applied to either pair.
    """

    def warp_label(label: torch.Tensor) -> torch.Tensor:
        """Warp a label map to the fixed grid with nearest interpolation."""
        return warp_image_3d(
            label.float(),
            target_displacement,
            interpolation_mode="nearest",
            padding_mode=padding_mode,
        ).round().long()

    fixed_ct_label = warp_label(moving_ct_label)
    fixed_pet_label = (warp_label(moving_pet_label)
                       if moving_pet_label is not None else None)
    synthesize_ct = functools.partial(
        ct_label_to_random_synthetic_ct,
        noise_std=augmentation.synthmorph_ct_noise_std,
        bias_amplitude=augmentation.synthmorph_ct_bias_amplitude)
    synthesize_pet = functools.partial(
        label_to_random_synthetic_pet,
        noise_std=augmentation.synthmorph_pet_noise_std,
        lesion_dropout_probability=(
            augmentation.synthmorph_pet_lesion_dropout_probability),
        false_hot_probability=augmentation.synthmorph_pet_false_hot_probability)
    drop_fov = functools.partial(
        apply_independent_fov_dropout,
        probability=augmentation.synthmorph_fov_dropout_probability,
        max_fraction=augmentation.synthmorph_fov_max_fraction)
    change_resolution = functools.partial(
        random_resolution_augmentation,
        min_scale=augmentation.synthmorph_min_resolution_scale)
    resolution_probability = (
        augmentation.synthmorph_resolution_augmentation_probability)

    # The order of these calls fixes the order of the random draws.
    moving_ct = synthesize_ct(moving_ct_label)
    fixed_ct = synthesize_ct(fixed_ct_label)
    moving_pet = synthesize_pet(moving_ct_label, moving_pet_label)
    fixed_pet = synthesize_pet(fixed_ct_label, fixed_pet_label)
    moving_ct, moving_pet, moving_fov = drop_fov(moving_ct, moving_pet)
    fixed_ct, fixed_pet, fixed_fov = drop_fov(fixed_ct, fixed_pet)
    moving_ct = change_resolution(moving_ct, probability=resolution_probability)
    fixed_ct = change_resolution(fixed_ct, probability=resolution_probability)
    moving_pet = change_resolution(moving_pet,
                                   probability=0.5 * resolution_probability)
    fixed_pet = change_resolution(fixed_pet,
                                  probability=0.5 * resolution_probability)
    return moving_ct, moving_pet, fixed_ct, fixed_pet, moving_fov or fixed_fov
